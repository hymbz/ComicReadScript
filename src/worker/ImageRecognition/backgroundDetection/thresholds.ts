/**
 * 所有可调参数统一放在此文件中。
 *

// ==================== 背景区域识别：中心跳过 ====================

/**
 * 用途：识别漫画背景区域时，将图片居中的多少比例视为“中间区域”并跳过。
 * 取值范围：0 ~ 1
 */
export const SKIP_CENTER_RATIO = 0.4;

// ==================== 背景区域识别：区域过滤 ====================

/**
 * 用途：面积小于该比例的 Region 会被删除。
 * 取值范围：0 ~ 1
 */
export const MIN_REGION_RATIO = 0.01;

// ==================== 背景区域识别：边缘种子生长 ====================

/**
 * 用途：边缘起点区域占图片长/宽的比例。
 * 取值范围：0 ~ 0.5
 */
export const EDGE_SEED_RATIO = 0.05;

// ==================== 背景色判断：边缘区域 ====================

/**
 * 用途：背景色判断时，边缘区域宽度占图片较短边的比例。
 * 取值范围：0 ~ 0.5
 */
export const EDGE_AREA_RATIO = 0.07;

/**
 * 用途：边缘区域内占比最大的背景区域需要达到的占比阈值。
 * 取值范围：0 ~ 1
 */
export const EDGE_AREA_REGION_RATIO = 0.15;

// ==================== 空白边缘判断 ====================

/**
 * 用途：一行/列中同一颜色的占比达到该阈值时，判定为空白边缘。
 * 取值范围：0 ~ 1
 */
export const BLANK_LINE_RATIO = 0.9;

/**
 * 用途：空白边缘扫描时，与参考背景色之间允许的最大 Oklab 色差。
 * 单位：Oklab 空间中的欧氏距离（ΔE），不是百分比。
 * 取值范围：0 ~ 1.51
 */
export const BLANK_MARGIN_COLOR_TOLERANCE = 0.2;

/**
 * 用途：整边累计允许的超色差像素数，占该边长度（左右边=图片高度，上下边=图片宽度）的比例。
 * 单位：比例值，0.01 表示 1%。
 * 取值范围：0 ~ 1
 */
export const BLANK_MARGIN_MAX_OUTLIER_RATIO = 0.005;

// ==================== Otsu 背景识别 ====================

/**
 * 用途：背景类在外围区域中的最低占比，低于该值视为无法可靠识别背景。
 * 取值范围：0 ~ 1
 */
export const BACKGROUND_MIN_RATIO = 0.6;

// ==================== Oklab 像素量化 ====================

/**
 * 用途：Oklab 像素量化级数，控制区域生长和代表色抹平色差的程度。
 * 取值范围：2 ~ 50
 */
export const LAB_QUANTIZE_LEVELS = 42;

// ==================== 灰度量化 ====================

/**
 * 用途：灰度量化级数，用于灰度图算法（otsu/simpleScan）对灰度取整的级数。
 * 取值范围：2 ~ 50
 */
export const GRAY_QUANTIZE_LEVELS = 32;

// ==================== HSV 分组：色相分桶 ====================

/**
 * 用途：色相分桶数量，每桶宽度为 360° / H_BUCKET_COUNT。
 * 取值范围：1 ~ 360
 */
export const H_BUCKET_COUNT = 24;

// ==================== HSV 分组：无彩色阈值 ====================

/**
 * 用途：低于该饱和度的颜色视为无彩色（灰/白/黑），归入单独桶，
 * 避免低饱和度颜色因 H 不稳定而被错误分桶。
 * 取值范围：0 ~ 1
 */
export const SATURATION_THRESHOLD = 0.03;

// ==================== HSV 分组：分组阈值 ====================

/**
 * 用途：桶内分组允许的最大综合距离，也用于相邻色相桶边界组的合并判断。
 * 取值范围：0 ~ 1
 */
export const HSV_GROUP_THRESHOLD = 0.12;

// ==================== HSV 分组：饱和度权重 ====================

/**
 * 用途：HSV 综合距离中饱和度差 ΔS 的权重。
 * 取值范围：>= 0
 */
export const SATURATION_WEIGHT = 0.6;

// ==================== 固定标记值 ====================

/** 中心保留区域的区域 id。 */
export const RESERVED_REGION_ID = -1;
